create schema if not exists memento;
revoke all on schema memento from public, anon, authenticated;
grant usage on schema memento to service_role;

-- Keep the shared project's existing API schemas and expose only Memento's
-- isolated schema in addition to them.
alter role authenticator set pgrst.db_schemas = 'public, graphql_public, memento';
notify pgrst, 'reload config';

create table memento.app_users (
  telegram_user_id bigint primary key check (telegram_user_id > 0),
  username text,
  first_name text,
  last_name text,
  starter_seeded_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table memento.vocabulary_items (
  id bigint generated by default as identity primary key,
  user_id bigint not null references memento.app_users (telegram_user_id) on delete cascade,
  term text not null check (char_length(btrim(term)) between 1 and 200),
  normalized_term text generated always as (lower(btrim(term))) stored,
  definition text not null check (char_length(btrim(definition)) between 1 and 500),
  status text not null default 'learning' check (status in ('learning', 'learned')),
  is_removed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, normalized_term)
);

create table memento.scheduling_states (
  vocabulary_id bigint primary key references memento.vocabulary_items (id) on delete cascade,
  repetitions integer not null default 0 check (repetitions >= 0),
  consecutive_correct integer not null default 0 check (consecutive_correct >= 0),
  interval_days integer not null default 0 check (interval_days >= 0),
  ease_factor numeric(4, 2) not null default 2.50 check (ease_factor >= 1.30),
  next_review_at timestamptz,
  last_reviewed_at timestamptz,
  updated_at timestamptz not null default now()
);

create table memento.rounds (
  id uuid primary key default gen_random_uuid(),
  user_id bigint not null references memento.app_users (telegram_user_id) on delete cascade,
  status text not null check (status in ('preparing', 'active', 'succeeded', 'failed', 'cancelled')),
  selected_vocabulary_ids bigint[] not null,
  total_items integer not null check (total_items between 1 and 10),
  first_attempt_correct integer,
  mistakes integer,
  created_at timestamptz not null default now(),
  activated_at timestamptz,
  completed_at timestamptz
);

create table memento.round_cards (
  id bigint generated by default as identity primary key,
  round_id uuid not null references memento.rounds (id) on delete cascade,
  vocabulary_id bigint not null references memento.vocabulary_items (id),
  position integer not null check (position >= 0),
  sentence text not null,
  answer text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) = 4),
  created_at timestamptz not null default now(),
  unique (round_id, vocabulary_id),
  unique (round_id, position)
);

create table memento.generation_usage (
  user_id bigint not null references memento.app_users (telegram_user_id) on delete cascade,
  usage_date date not null,
  attempts integer not null default 0 check (attempts between 0 and 5),
  updated_at timestamptz not null default now(),
  primary key (user_id, usage_date)
);

create index vocabulary_items_user_status_idx
  on memento.vocabulary_items (user_id, status, is_removed);
create index scheduling_states_due_idx
  on memento.scheduling_states (next_review_at)
  where next_review_at is not null;
create index rounds_user_created_idx
  on memento.rounds (user_id, created_at desc);
create index round_cards_round_idx on memento.round_cards (round_id);
create unique index rounds_one_open_per_user_idx
  on memento.rounds (user_id)
  where status in ('preparing', 'active');


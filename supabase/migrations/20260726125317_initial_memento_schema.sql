create or replace function memento.reserve_generation_attempt(
  requested_user_id bigint,
  requested_date date
) returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  next_attempts integer;
begin
  insert into memento.generation_usage (user_id, usage_date, attempts)
  values (requested_user_id, requested_date, 1)
  on conflict (user_id, usage_date) do update
    set attempts = memento.generation_usage.attempts + 1,
        updated_at = now()
    where memento.generation_usage.attempts < 5
  returning attempts into next_attempts;

  return next_attempts is not null;
end;
$$;

create or replace function memento.complete_round(
  requested_round_id uuid,
  requested_user_id bigint,
  first_attempt_results jsonb,
  requested_mistakes integer,
  reviewed_at timestamptz default now()
) returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  target_round memento.rounds%rowtype;
  result_record record;
  state_record memento.scheduling_states%rowtype;
  new_repetitions integer;
  new_consecutive integer;
  new_interval integer;
  new_ease numeric(4, 2);
  correct_count integer := 0;
begin
  select * into target_round
  from memento.rounds
  where id = requested_round_id and user_id = requested_user_id
  for update;

  if not found then
    raise exception 'ROUND_NOT_FOUND';
  end if;
  if target_round.status = 'succeeded' then
    return jsonb_build_object('alreadyCompleted', true);
  end if;
  if target_round.status <> 'active' then
    raise exception 'ROUND_STALE';
  end if;
  if jsonb_typeof(first_attempt_results) <> 'array'
     or jsonb_array_length(first_attempt_results) <> target_round.total_items then
    raise exception 'INVALID_RESULTS';
  end if;
  if requested_mistakes < 0 or requested_mistakes > 2 then
    raise exception 'INVALID_RESULTS';
  end if;
  if exists (
    select 1
    from jsonb_to_recordset(first_attempt_results) as r(vocabulary_id bigint, correct boolean)
    where not (r.vocabulary_id = any(target_round.selected_vocabulary_ids))
  ) or (
    select count(distinct r.vocabulary_id)
    from jsonb_to_recordset(first_attempt_results) as r(vocabulary_id bigint, correct boolean)
  ) <> target_round.total_items then
    raise exception 'INVALID_RESULTS';
  end if;
  if exists (
    select 1
    from memento.vocabulary_items v
    where v.id = any(target_round.selected_vocabulary_ids)
      and (v.user_id <> requested_user_id or v.status <> 'learning' or v.is_removed)
  ) then
    raise exception 'ROUND_STALE';
  end if;

  for result_record in
    select * from jsonb_to_recordset(first_attempt_results)
      as r(vocabulary_id bigint, correct boolean)
  loop
    select * into state_record
    from memento.scheduling_states
    where vocabulary_id = result_record.vocabulary_id
    for update;

    if result_record.correct then
      correct_count := correct_count + 1;
      new_repetitions := state_record.repetitions + 1;
      new_consecutive := state_record.consecutive_correct + 1;
      new_ease := greatest(1.30, state_record.ease_factor + 0.10);
      new_interval := case
        when new_repetitions = 1 then 1
        when new_repetitions = 2 then 6
        else greatest(1, round(state_record.interval_days * new_ease)::integer)
      end;
    else
      new_repetitions := 0;
      new_consecutive := 0;
      new_ease := greatest(1.30, state_record.ease_factor - 0.20);
      new_interval := 1;
    end if;

    update memento.scheduling_states
    set repetitions = new_repetitions,
        consecutive_correct = new_consecutive,
        interval_days = new_interval,
        ease_factor = new_ease,
        next_review_at = reviewed_at + make_interval(days => new_interval),
        last_reviewed_at = reviewed_at,
        updated_at = reviewed_at
    where vocabulary_id = result_record.vocabulary_id;

    if new_consecutive >= 3 and new_interval >= 14 then
      update memento.vocabulary_items
      set status = 'learned', updated_at = reviewed_at
      where id = result_record.vocabulary_id;
    end if;
  end loop;

  update memento.rounds
  set status = 'succeeded',
      first_attempt_correct = correct_count,
      mistakes = requested_mistakes,
      completed_at = reviewed_at
  where id = requested_round_id;

  return jsonb_build_object(
    'alreadyCompleted', false,
    'firstAttemptCorrect', correct_count,
    'total', target_round.total_items
  );
end;
$$;


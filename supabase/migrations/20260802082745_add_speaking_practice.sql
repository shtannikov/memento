create or replace function memento.promote_vocabulary_to_practicing(
  requested_vocabulary_id bigint,
  requested_user_id bigint,
  requested_app_id text,
  promoted_at timestamptz default now()
) returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  target memento.vocabulary_items%rowtype;
  next_rank bigint;
begin
  select * into target
  from memento.vocabulary_items
  where id = requested_vocabulary_id
    and user_id = requested_user_id
    and app_id = requested_app_id
    and not is_removed
  for update;

  if not found then raise exception 'VOCABULARY_NOT_FOUND'; end if;
  if target.status = 'learned' then return false; end if;
  if target.status = 'practicing' then return true; end if;

  select coalesce(max(state.practice_rank), 0) + 1024 into next_rank
  from memento.speaking_states state
  join memento.vocabulary_items item on item.id = state.vocabulary_id
  where item.user_id = requested_user_id
    and item.app_id = requested_app_id
    and item.status = 'practicing'
    and not item.is_removed;

  insert into memento.speaking_states (vocabulary_id, practice_rank, updated_at)
  values (target.id, next_rank, promoted_at)
  on conflict (vocabulary_id) do update
    set practice_rank = excluded.practice_rank,
        correct_uses = 0,
        incorrect_uses = 0,
        missed = 0,
        first_seen_at = null,
        last_seen_at = null,
        last_used_at = null,
        updated_at = promoted_at;

  update memento.vocabulary_items
  set status = 'practicing', updated_at = promoted_at
  where id = target.id;
  return true;
end;
$$;

create or replace function memento.prepare_learning_reset(
  requested_user_id bigint,
  requested_app_id text,
  requested_at timestamptz default now()
) returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  item_count integer;
  open_task boolean;
begin
  perform 1 from memento.user_apps
  where user_id = requested_user_id and app_id = requested_app_id
  for update;
  if not found then raise exception 'USER_NOT_FOUND'; end if;

  select count(*) into item_count
  from memento.vocabulary_items
  where user_id = requested_user_id and app_id = requested_app_id
    and status = 'learning' and not is_removed;

  select exists (
    select 1 from memento.speaking_tasks
    where user_id = requested_user_id and app_id = requested_app_id
      and status in ('preparing', 'ready', 'active')
  ) into open_task;

  insert into memento.pending_resets (
    user_id, app_id, learning_count, has_open_task, requested_at, expires_at
  ) values (
    requested_user_id, requested_app_id, item_count, open_task,
    requested_at, requested_at + interval '10 minutes'
  ) on conflict (user_id, app_id) do update
    set learning_count = excluded.learning_count,
        has_open_task = excluded.has_open_task,
        requested_at = excluded.requested_at,
        expires_at = excluded.expires_at;

  return jsonb_build_object('learningCount', item_count, 'hasOpenTask', open_task);
end;
$$;

